#include "../benchmark/DeXOR/DeXOR.hpp"
#include <cmath>
#include <cstdlib>
#include <limits>
#include <iostream>
#include <random>
#include <string>

namespace dx = gef_compressors::dexor;
static void require(bool condition, const char* message) {
    if (!condition) { std::cerr << message << '\n'; std::exit(1); }
}
// Upstream DeXOR accepts decimal encodings whose reconstruction is only close
// to the input (DoubleDeXOREncoder.java:113), so round trips are checked
// against a tolerance; full and prefix decoding must agree bit-for-bit.
static size_t check(const std::vector<double>& values, double tolerance = 1e-9) {
    const auto bytes = dx::compress(values);
    const auto restored = dx::decompress(bytes, values.size());
    require(restored.size() == values.size(), "size mismatch");
    size_t inexact = 0;
    for (size_t i = 0; i < values.size(); ++i) {
        if (dx::detail::bits(restored[i]) == dx::detail::bits(values[i])) continue;
        ++inexact;
        if (std::isnan(values[i])) { // upstream treats NaN as zero (comp(NaN,0)==0)
            require(dx::detail::bits(restored[i]) == 0, "NaN not decoded as upstream +0.0");
            continue;
        }
        require(std::abs(restored[i]-values[i]) <= tolerance*std::max(1.0, std::abs(values[i])),
                "round trip outside tolerance");
    }
    return inexact;
}
static void check_prefixes(const std::vector<double>& values) {
    const auto bytes = dx::compress(values);
    const auto full = dx::decompress(bytes, values.size());
    for (size_t count = 0; count <= values.size(); ++count) {
        const auto restored = dx::decompress_prefix(bytes, values.size(), count);
        require(restored.size() == count, "prefix size mismatch");
        for (size_t i = 0; i < count; ++i)
            require(dx::detail::bits(restored[i]) == dx::detail::bits(full[i]),
                    "prefix decode differs from full decode");
    }
}
static void check_java(const std::vector<double>& values, const std::string& hex,
                       const std::vector<uint64_t>& java_decoded) {
    const auto encoded = dx::compress(values);
    require(encoded.size() == 8+hex.size()/2, "official Java fixture size mismatch");
    for (size_t i = 0; i < hex.size()/2; ++i)
        require(encoded[8+i] == std::stoul(hex.substr(2*i, 2), nullptr, 16), "official Java bitstream mismatch");
    if (java_decoded.empty()) return;
    const auto restored = dx::decompress(encoded, values.size());
    for (size_t i = 0; i < values.size(); ++i)
        require(dx::detail::bits(restored[i]) == java_decoded[i], "official Java decoder output mismatch");
}
int main() {
    // Generated by the unmodified official Java Native encoder, commit 06128b3.
    // Includes all four control cases and exception-handler exponent state.
    const std::vector<double> golden = {1,2,3,10,11,11,11,-11,-12,0,0.5,0.25,
        1.2345678901234567,1.2345678901234567,0.25};
    const std::string hex = "4634a99518941142482d12480098d4914ce1e06521462cfde1e06521462cfda0";
    check_java(golden, hex, {});
    const auto encoded = dx::compress(golden);
    // Second official fixture: high-precision (Double.toString) tail search and
    // two inexact reconstructions; also pins the stock Java decoder output.
    check_java({0.1234567890123456,0.1234567890123457,3.14159265358979,92.265932524778194,
        92.265932524778179,-1.6611623539523179,-1.6611623539523159,999.5,0.30000000000000004,
        0.1,1e-5,2.5e-7,64.5487,64.56,19.0000005,19.0},
        "e7f7f35ba6e8decb3af9add3746f6610df476e79da8920c3ff47275d5481260c2ff7ff5283df3f24a67bd4a0f7cf"
        "c9295134ce1740034623d600011890064836765bc90b0d996a6570a500",
        {UINT64_C(0x3fbf9add3746f659),UINT64_C(0x3fbf9add3746f661),UINT64_C(0x400921fb54442d11),
         UINT64_C(0x4057110509da375e),UINT64_C(0x4057110509da3763),UINT64_C(0xbffa941ef9f92533),
         UINT64_C(0xbffa941ef9f9252a),UINT64_C(0x408f3c0000000000),UINT64_C(0x3fd3333333333334),
         UINT64_C(0x3fb999999999999a),UINT64_C(0x3ee4f8b588e368f1),UINT64_C(0x3e90c6f7a0b5ed8d),
         UINT64_C(0x4050231de69ad42c),UINT64_C(0x405023d70a3d70a4),UINT64_C(0x4033000008637bd0),
         UINT64_C(0x4033000000000000)});
    check(golden);
    check_prefixes(golden);
    check_prefixes({});
    check_prefixes({0.0,-0.0,0.0,-0.0});
    check_prefixes({19.0000005,19.0,19.0000005,64.5487,64.56,88.1537,88.1479});
    check({});
    check({0.0});
    check({-0.0});
    check({0.0,-0.0,0.0,-0.0});
    check(std::vector<double>(10000, 42.125));
    // Upstream's 1e-6 integer test in the tail search turns 19.0000005 into 19
    // (relative error 2.6e-8); the port reproduces this documented anomaly.
    {
        const std::vector<double> anomaly = {19.0000005,19.0,19.0000005,64.5487,64.56,88.1537,88.1479};
        const auto restored = dx::decompress(dx::compress(anomaly), anomaly.size());
        require(restored[0] == 19.0 && restored[2] == 19.0, "upstream rounding anomaly not reproduced");
        for (size_t i = 3; i < anomaly.size(); ++i)
            require(std::abs(restored[i]-anomaly[i]) <= 1e-9*std::abs(anomaly[i]), "decimal value outside tolerance");
    }
    require(check({std::numeric_limits<double>::infinity(), 1.5, -std::numeric_limits<double>::infinity()}, 0) == 0,
            "infinities must round-trip exactly (exception encoding)");
    std::vector<double> values;
    for (uint64_t raw : {uint64_t(1), uint64_t(0x8000000000000001),
            uint64_t(0x000fffffffffffff), uint64_t(0x0010000000000000),
            uint64_t(0x7fefffffffffffff), uint64_t(0xffefffffffffffff),
            uint64_t(0x7ff0000000000000), uint64_t(0xfff0000000000000),
            uint64_t(0x7ff8000000000000), uint64_t(0x7ff8000000000001),
            uint64_t(0xfff800000000ffff), uint64_t(0x7ff0000000000001)})
        values.push_back(dx::detail::value(raw));
    check(values);
    check_prefixes(values);
    std::mt19937_64 random(0xdec0de);
    values.clear();
    for (size_t i = 0; i < 100000; ++i) values.push_back(dx::detail::value(random()));
    check(values);
    values.clear();
    for (size_t i = 0; i < 100000; ++i)
        values.push_back(static_cast<int64_t>(random()%2000000)-1000000 + (i%1000)/1000.0);
    check(values);
    for (int exponent = -300; exponent <= 300; ++exponent) {
        values.clear();
        const double scale = std::pow(10.0, exponent);
        for (size_t i = 0; i < 100; ++i) values.push_back((i%2 ? -1.0 : 1.0) * (1+i/1000.0)*scale);
        check(values);
    }
    // Truncation, forged count, trailing garbage and nonzero padding are rejected.
    for (size_t n = 0; n < encoded.size(); ++n) {
        bool failed = false;
        try { dx::decompress(std::vector<uint8_t>(encoded.begin(), encoded.begin()+n), golden.size()); }
        catch (const std::runtime_error&) { failed = true; }
        require(failed, "truncated stream accepted");
    }
    bool failed = false;
    try { dx::decompress(encoded, golden.size()+1); }
    catch (const std::runtime_error&) { failed = true; }
    require(failed, "wrong count accepted");
    auto trailing = encoded;
    trailing.push_back(0);
    failed = false;
    try { dx::decompress(trailing, golden.size()); }
    catch (const std::runtime_error&) { failed = true; }
    require(failed, "trailing bytes accepted");
    auto padding = dx::compress({0.0});
    padding.back() |= 1;
    failed = false;
    try { dx::decompress(padding, 1); }
    catch (const std::runtime_error&) { failed = true; }
    require(failed, "nonzero padding accepted");
    // Proper prefixes must not decode the suffix: they still succeed when its
    // last byte is missing, while full decompression must reject this stream.
    auto truncated_tail = encoded;
    truncated_tail.pop_back();
    const auto first = dx::decompress_prefix(truncated_tail, golden.size(), 1);
    require(first.size() == 1 && first[0] == golden[0], "prefix read the unrequested tail");
    std::vector<uint8_t> header_only(encoded.begin(), encoded.begin()+8);
    require(dx::decompress_prefix(header_only, golden.size(), 0).empty(), "empty prefix read payload");
    failed = false;
    try { dx::decompress_prefix(encoded, golden.size()+1, 0); }
    catch (const std::runtime_error&) { failed = true; }
    require(failed, "empty prefix accepted wrong total count");
    failed = false;
    try { dx::decompress_prefix(encoded, golden.size(), golden.size()+1); }
    catch (const std::invalid_argument&) { failed = true; }
    require(failed, "prefix larger than total accepted");
    failed = false;
    try { dx::decompress_prefix(padding, 1, 1); }
    catch (const std::runtime_error&) { failed = true; }
    require(failed, "full prefix skipped framing validation");
    std::cout << "DeXOR: official Java fixtures and upstream-behaviour regression tests passed\n";
}
