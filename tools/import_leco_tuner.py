"""Regenerate benchmark/LeCo/NativeTuning.hpp from the pinned LeCo submodule.

The authors' only published implementation of the sampling-based fixed
partition-size search (paper Section 3.2.1) is pick_block_size() in
headers/search_hyper.h. We copy it verbatim except for the replacements below,
each of which must match exactly once. See docs/leco.md.
"""
from pathlib import Path
import hashlib, json

root = Path(__file__).resolve().parents[1]
src = root / 'lib/Learn-to-Compress/headers/search_hyper.h'
s = src.read_text()

REPLACEMENTS = [
    # Build: bind the factory lookup to the uint64 Leco_int adapter below
    # instead of the full (uint32-only) codec factory.
    ('#include "codecfactory.h"\n', '', 'use local uint64 Leco_int adapter instead of codecfactory.h'),
    ('using namespace Codecset;\n', '', 'use local uint64 Leco_int adapter instead of codecfactory.h'),
    # 64-bit: our inputs are 64-bit integers.
    ('uint32_t * data', 'const uint64_t * data', 'uint64 input pointer'),
    # 64-bit: normalise by 8-byte values; with 4 the ratio of a 64-bit sample
    # can exceed the initial minimum 1.0 and no candidate would be selected.
    ('(4 * times * sample_size * 1.0)', '(8 * times * sample_size * 1.0)', '8-byte denominator for uint64'),
]
for old, new, _ in REPLACEMENTS:
    if s.count(old) != 1:
        raise SystemExit(f'expected exactly one occurrence of {old!r}')
    s = s.replace(old, new)

header = '''#pragma once
// GENERATED by tools/import_leco_tuner.py from lib/Learn-to-Compress/headers/search_hyper.h
// (pinned 28bf8bf). Only the replacements listed in upstream-tuner.json differ.
#include <cstdint>
#include <cstdlib>
#include <string>
#include <vector>
#include "piecewise_fix_integer_template.h"
namespace leco_native_tuning {
// Adapter exposing the original uint64 Leco_int through the factory API used by pick_block_size.
struct SampleCodec {
    Codecset::Leco_int<uint64_t> codec;
    void init(int blocks, int block_size, int) { codec.init(blocks, block_size); }
    uint8_t* encodeArray8(const uint64_t* p, size_t n, uint8_t* out, size_t block) {
        return codec.encodeArray8_int(p, n, out, block);
    }
};
using IntegerCODEC = SampleCodec;
struct CODECFactory {
    static SampleCodec* getFromName(const std::string&) {
        static SampleCodec value;
        value = SampleCodec{};
        return &value;
    }
};
'''
footer = '''
// Called once per dataset, as in the authors' search_hyper_regress.cpp: candidate grid
// {200..10000}, one 1% sample. Upstream runs one dataset per process with rand() unseeded,
// which equals srand(1); our harness runs several datasets per process, so reseed to keep that.
inline size_t choose(const uint64_t* data, size_t n) {
    int candidates[7] = {200, 400, 800, 1600, 3200, 6400, 10000};
    // An empty 1% sample (n < 100) cannot rank candidates (upstream asserts); n fits one partition.
    if (n < 100) return size_t(candidates[0]);
    std::srand(1);
    return size_t(candidates[pick_block_size(candidates, 7, 1, 0.01, int(n), data, "leco_int_fix").select]);
}
} // namespace leco_native_tuning
'''
(root / 'benchmark/LeCo/NativeTuning.hpp').write_text(header + s + footer)
(root / 'benchmark/LeCo/upstream-tuner.json').write_text(json.dumps({
    'commit': '28bf8bf3d0dd721baa2d6c714d8b454529af41aa',
    'source': 'headers/search_hyper.h',
    'sha256': hashlib.sha256(src.read_bytes()).hexdigest(),
    'changes': sorted({why for _, _, why in REPLACEMENTS}),
}, indent=2) + '\n')
